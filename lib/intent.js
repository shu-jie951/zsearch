/**
 * 开头口语前缀。
 *
 * 判据：去掉之后**剩余部分仍然是一个能搜的词**，才算去掉。
 * 「求」去掉后剩空 → 保留原词（用户就是想搜「求」，虽然少见，但不能吞掉输入）。
 */
const LEAD_FILLER =
  /^(?:请问一下|请问|请教一下|请教|麻烦|跪求|求求|求助|求资源|求个|求一份|求|大佬们?|大神们?|好心人|谁有|有没有|有木有|哪里能下载|哪里可以下载|哪里下载|哪儿能下载|在哪儿下载|怎么下载|帮我找|帮忙找|帮我搜|帮找|找一下|找找|想找|我想要|我要|需要|来个|来一份)/;

/**
 * 结尾用途后缀。
 *
 * 这些词描述的是「我要拿它干什么」，不是「我找的是什么」，留在查询里
 * 只会稀释匹配（上游是按标题做子串匹配的）。实测「有没有庆余年的资源」
 * 直接 0 条，「庆余年」几十条 —— 五个字的后缀就足以让结果清零。
 */
const TAIL_FILLER =
  /(?:的)?(?:资源|链接|链接地址|地址|下载|网盘|云盘|种子|磁力|在线看|在线观看|观看|高清|超清|免费|无删减|完整版|谢谢|感谢|多谢|感恩|急求|拜托|大佬们?|大神们?|老哥们?|楼主|各位|大家|行吗|好吗|可以吗|有没有|呢|啊|呀|吧|吗|哈)+$/;

/**
 * 中间的口语化连接：`X的资源` / `X的链接`。
 *
 * ⚠️ 只匹配「的/之 + 明确名词」，不能写成单个 `的`——
 * 那样会把「目的」「的确」「的士」里的字一起吃掉，把用户的词改坏。
 */
const MID_FILLER = /(?:之|的)(?:资源|链接|地址|网盘|云盘|种子|磁力|分享|下载)/g;

